  /* Подставляет BOT_URL / REPO_URL во все элементы с data-link и data-link-text */
  applyLinks() {
    const map = { bot: this.BOT_URL, repo: this.REPO_URL };

    document.querySelectorAll("[data-link]").forEach((el) => {
      const url = map[el.dataset.link];
      if (url) el.setAttribute("href", url);
    });

    document.querySelectorAll("[data-link-text]").forEach((el) => {
      const url = map[el.dataset.linkText];
      if (url) el.textContent = url.replace(/^https?:\/\//, "");
    });
  },

  /* Текущий год в футере */
  setYear() {
    const year = String(new Date().getFullYear());
    document.querySelectorAll("[data-year]").forEach((el) => {
      el.textContent = year;
    });
  },

  /* Пользователь просит уменьшить движение? Проверяем каждый раз — настройка может смениться */
